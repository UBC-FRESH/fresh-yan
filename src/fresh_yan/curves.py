"""Carbon yield curve generation (libCBM single-stand trajectories).

Managed (transition) curves are generated by *simulating the clearcut* instead of
reading a spun-up post-disturbance state:

- the stand grows on its natural trajectory to ``rotation_age``;
- a harvest event transfers the pools per CBM's disturbance matrix (merchandise
  removed, slash to dead pools, disturbance emissions) -- so the age-0 state is
  conservation-consistent with the stand's own pre-harvest state;
- the stand regrows on the managed yield curve.

``mode='single'`` uses one clearcut (age-0 = first-rotation post-harvest state);
``mode='cycle'`` repeats the clearcut every ``rotation_age`` years and extracts the
last cycle (age-0 = rotation-cycle equilibrium).  Natural curves are the spun-up
no-harvest trajectories (initial landscape convention).
"""

from __future__ import annotations

import json
import os
import sys

import pandas as pd

from .cbm import run_cbm
from .model import (
    all_fluxes,
    all_pools,
    biomass_pools,
    build_model,
    disturbance_type_mapping,
    dom_pools,
    ecosystem_pools,
    gross_growth,
    model_paths,
    to_cbm_sit,
    total_emission,
)
from .records import provenance

ROTATION_AGE = 120  # base-scenario area-weighted median harvest age (110) / trade-off (120-125)
N_STEPS = 700


def _natural_parent(fm, dtype_key, harvest_acode="harvest"):
    """Find the natural (pre-harvest) dtype that transitions into ``dtype_key``."""
    for cand in fm.dtypes:
        dt = fm.dt(cand)
        for (acode, sage) in dt.transitions:
            if acode != harvest_acode:
                continue
            for target in dt.transitions[acode, sage]:
                tmask = target[0]
                dtk = [t if tmask[i] == "?" else tmask[i] for i, t in enumerate(cand)]
                if tuple(dtk) == tuple(dtype_key):
                    return cand
    return None


def _single_stand_inventory(sit_tables, dtype_key, age=1, area=1.0,
                            historic_disturbance="fire"):
    inv = sit_tables["sit_inventory"]
    theme_cols = [c for c in inv.columns if c.startswith("theme")]
    mask = True
    for c, v in zip(theme_cols, dtype_key, strict=False):
        mask = mask & (inv[c].astype(str) == str(v))
    sub = inv[mask].iloc[[0]].copy()
    sub["age"] = age
    sub["area"] = area
    sub["historic_disturbance"] = historic_disturbance
    sub["last_pass_disturbance"] = historic_disturbance
    return sub


def _clearcut_event(events, inventory_row, year, area=1.0):
    row = {}
    theme_cols = [c for c in events.columns if c.startswith("theme")]
    for c in theme_cols:
        row[c] = inventory_row.iloc[0][c]
    row["species"] = inventory_row.iloc[0]["species"]
    row["using_age_class"] = "FALSE"
    for c in ["min_softwood_age", "max_softwood_age", "min_hardwood_age", "max_hardwood_age"]:
        row[c] = -1
    mid = list(events.columns[events.columns.get_loc("MinYearsSinceDist"):
                              events.columns.get_loc("efficiency")])
    for c in mid:
        row[c] = -1
    row["efficiency"] = 1
    row["sort_type"] = 3
    row["target_type"] = "A"
    row["target"] = area
    row["disturbance_type"] = "harvest"
    row["disturbance_year"] = year
    return pd.concat([events, pd.DataFrame([row])], ignore_index=True)


def _summarize(out):
    pi = out.classifiers.to_pandas().merge(
        out.pools.to_pandas(), left_on=["identifier", "timestep"],
        right_on=["identifier", "timestep"])
    fi = out.classifiers.to_pandas().merge(
        out.flux.to_pandas(), left_on=["identifier", "timestep"],
        right_on=["identifier", "timestep"])
    pi = pi.set_index("timestep")
    fi = fi.set_index("timestep")
    pi["ecosystem"] = pi[ecosystem_pools].sum(axis=1)
    pi["biomass"] = pi[biomass_pools].sum(axis=1)
    pi["DOM"] = pi[dom_pools].sum(axis=1)
    fi["total_emission"] = fi[total_emission].sum(axis=1)
    fi["gross_growth"] = fi[gross_growth].sum(axis=1)
    fi["net_emission"] = fi["total_emission"] - fi["gross_growth"]
    return pi, fi


def _run_stand(sit_config, sit_tables, inventory_row, events, n_steps):
    tables = dict(sit_tables)
    tables["sit_inventory"] = inventory_row
    tables["sit_events"] = events
    return run_cbm(sit_config, tables, n_steps=n_steps)


def generate(out_dir: str = "curves", rotation_age: int = ROTATION_AGE,
             n_steps: int = N_STEPS, mode: str = "cycle", tsa: str = "tsa24",
             model_name: str | None = None, model_path: str | None = None,
             section_units: str = "years", harvest_acode: str = "harvest") -> None:
    """Generate carbon yield curves (pools + fluxes) for every model dtype.

    ``mode``: ``'single'`` (one clearcut) or ``'cycle'`` (repeated clearcuts at
    ``rotation_age``; extract the last cycle).  ``tsa``/``model_name``/``model_path``
    select the management unit (defaults: TSA 24; see :func:`fresh_yan.model.model_paths`);
    ``section_units``/``harvest_acode`` match the section-file contract of femic
    ``export ws3-sections`` exports (``"periods"``/``"cc"``).
    """
    assert mode in ("single", "cycle")
    model_name, model_path = model_paths(tsa, model_name, model_path)
    # Capture provenance before writing into curves/ so fy_commit is not polluted by
    # the generated outputs themselves.
    prov = provenance()
    fm = build_model(model_name=model_name, model_path=model_path,
                     section_units=section_units)
    mapping = disturbance_type_mapping(fm, harvest_acode=harvest_acode)
    sit_config, sit_tables = to_cbm_sit(fm, mapping)
    empty_events = sit_tables["sit_events"]

    natural_keys = [k for k in fm.dtypes if k[2] == k[4]]
    managed_keys = [k for k in fm.dtypes if k[2] != k[4]]
    print(f"{len(natural_keys)} natural dtypes, {len(managed_keys)} managed dtypes", flush=True)

    pool_curves: dict[str, pd.DataFrame] = {}
    flux_curves: dict[str, pd.DataFrame] = {}

    # --- natural curves: spun-up, no harvest ---
    for key in natural_keys:
        inv = _single_stand_inventory(sit_tables, key, historic_disturbance="fire")
        out = _run_stand(sit_config, sit_tables, inv, empty_events, n_steps)
        pi, fi = _summarize(out)
        pool_curves[" ".join(key)] = pi[all_pools]
        flux_curves[" ".join(key)] = fi[all_fluxes]
        print(f"  natural {key}: done", flush=True)

    # --- managed curves: simulated clearcut(s) ---
    for key in managed_keys:
        parent = _natural_parent(fm, key, harvest_acode)
        if parent is None:
            print(f"  managed {key}: NO NATURAL PARENT - skipped", flush=True)
            continue
        inv = _single_stand_inventory(sit_tables, parent, historic_disturbance="fire")
        events = empty_events
        if mode == "single":
            events = _clearcut_event(events, inv, rotation_age)
            total_steps = rotation_age + n_steps
            cut_at = rotation_age
        else:
            n_rot = 5
            inv_managed = inv.copy()
            inv_managed.iloc[0, inv_managed.columns.get_loc("theme4")] = key[4]
            for i in range(1, n_rot + 1):
                # first cut: natural stand; later cuts: managed stand (theme4 differs)
                src = inv if i == 1 else inv_managed
                events = _clearcut_event(events, src, rotation_age * i)
            total_steps = rotation_age * n_rot + n_steps
            cut_at = rotation_age * n_rot
        out = _run_stand(sit_config, sit_tables, inv, events, total_steps)
        pi, fi = _summarize(out)
        # pre-event state (for conservation checks)
        pre = pi.loc[cut_at - 1]
        post = pi.loc[cut_at]
        merch = pre["SoftwoodMerch"] + pre["HardwoodMerch"]
        print(f"  managed {key} (from {parent}): pre eco={pre['ecosystem']:.2f} "
              f"merch={merch:.2f} post eco={post['ecosystem']:.2f} "
              f"drop={pre['ecosystem'] - post['ecosystem']:.2f}", flush=True)
        # re-index the post-clearcut trajectory to curve age
        pi2 = pi.loc[cut_at:cut_at + n_steps].copy()
        pi2.index = pi2.index - cut_at
        fi2 = fi.loc[cut_at:cut_at + n_steps].copy()
        fi2.index = fi2.index - cut_at
        pool_curves[" ".join(key)] = pi2[all_pools]
        flux_curves[" ".join(key)] = fi2[all_fluxes]

    c_curves_p = pd.concat(pool_curves, names=["dtype_key", "timestep"])
    c_curves_f = pd.concat(flux_curves, names=["dtype_key", "timestep"])
    c_curves_p["ecosystem"] = c_curves_p[ecosystem_pools].sum(axis=1)
    c_curves_p["biomass"] = c_curves_p[biomass_pools].sum(axis=1)
    c_curves_p["DOM"] = c_curves_p[dom_pools].sum(axis=1)
    c_curves_p["merch"] = c_curves_p["SoftwoodMerch"] + c_curves_p["HardwoodMerch"]
    c_curves_f["total_emission"] = c_curves_f[total_emission].sum(axis=1)
    c_curves_f["gross_growth"] = c_curves_f[gross_growth].sum(axis=1)
    c_curves_f["net_emission"] = c_curves_f["total_emission"] - c_curves_f["gross_growth"]

    os.makedirs(out_dir, exist_ok=True)
    c_curves_p.to_pickle(os.path.join(out_dir, "c_curves_p.pkl"))
    c_curves_f.to_pickle(os.path.join(out_dir, "c_curves_f.pkl"))
    with open(os.path.join(out_dir, "provenance.json"), "w", encoding="utf-8") as fh:
        json.dump({"tsa": tsa, "model_name": model_name, "model_path": model_path,
                   "rotation_age": rotation_age, "n_steps": n_steps, "mode": mode,
                   "section_units": section_units, "harvest_acode": harvest_acode,
                   **prov}, fh, indent=2)
    print(f"Wrote {mode} carbon curves to {out_dir} "
          f"({len(c_curves_p)} pool rows, {len(c_curves_f)} flux rows)")


if __name__ == "__main__":
    generate(mode=sys.argv[1] if len(sys.argv) > 1 else "cycle")
